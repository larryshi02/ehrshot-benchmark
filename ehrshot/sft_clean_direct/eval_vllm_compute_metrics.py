#!/usr/bin/env python3
"""
Compute Evaluation Metrics (AUROC, AUPRC) from Model Predictions

Reads predictions.csv files generated by eval_vllm_direct.py and computes
AUROC, AUPRC with bootstrap confidence intervals for each task.

Usage:
    python eval_vllm_compute_metrics.py --eval_root eval_results/originalEHR_base

Expected Input Structure:
    eval_root/
    ├── acute_mi/
    │   ├── predictions.csv      # columns: ground_truth, probability_score
    │   └── run_stats.json       # optional runtime stats
    ├── hyperlipidemia/
    ├── hypertension/
    └── pancreatic_cancer/

Output:
    eval_root/
    ├── metrics_summary.csv      # AUROC/AUPRC for all tasks in one table
    └── {task}/summary.json      # Detailed metrics per task
"""

import os
import json
import argparse
import pandas as pd
import numpy as np
from sklearn.metrics import roc_auc_score, precision_recall_curve, auc
from typing import Dict, List, Optional


TASKS = ['acute_mi', 'pancreatic_cancer', 'hypertension', 'hyperlipidemia']


# =============================================================================
# METRIC COMPUTATION
# =============================================================================

def compute_auprc(y_true: np.ndarray, y_scores: np.ndarray) -> float:
    """Compute Area Under Precision-Recall Curve."""
    precision, recall, _ = precision_recall_curve(y_true, y_scores)
    return auc(recall, precision)


def bootstrap_ci(
    y_true: np.ndarray, 
    y_scores: np.ndarray, 
    metric_fn, 
    n_bootstraps: int = 1000,
    seed: int = 42
) -> List[float]:
    """
    Compute metric with 95% bootstrap confidence interval.
    
    Returns: [mean, ci_lower (2.5%), ci_upper (97.5%)]
    """
    rng = np.random.RandomState(seed)
    scores = []
    
    y_true = np.asarray(y_true)
    y_scores = np.asarray(y_scores)
    n = len(y_scores)
    
    for _ in range(n_bootstraps):
        idx = rng.randint(0, n, n)
        
        # Skip if bootstrap sample has only one class
        if len(np.unique(y_true[idx])) < 2:
            continue
        
        try:
            scores.append(metric_fn(y_true[idx], y_scores[idx]))
        except ValueError:
            continue
    
    if not scores:
        return [0.0, 0.0, 0.0]

    return [
        float(np.mean(scores)),
        float(np.percentile(scores, 2.5)),
        float(np.percentile(scores, 97.5))
    ]


def compute_optimal_f1(y_true: np.ndarray, y_scores: np.ndarray) -> Dict:
    """
    Find threshold that maximizes F1 and return associated metrics.
    
    Returns: {optimal_threshold, f1, precision, recall}
    """
    precision, recall, thresholds = precision_recall_curve(y_true, y_scores)
    
    # Compute F1 at each threshold
    with np.errstate(divide='ignore', invalid='ignore'):
        f1 = np.where(
            (precision + recall) > 0,
            2 * precision * recall / (precision + recall),
            0.0
        )
    
    best_idx = np.argmax(f1)
    
    return {
        "optimal_threshold": float(thresholds[best_idx]) if best_idx < len(thresholds) else 0.5,
        "f1": float(f1[best_idx]),
        "precision": float(precision[best_idx]),
        "recall": float(recall[best_idx])
    }


# =============================================================================
# TASK PROCESSING
# =============================================================================

def process_task_predictions(task_dir: str, task_name: str) -> Optional[Dict]:
    """
    Load predictions.csv for a task and compute all metrics.
    
    Args:
        task_dir: Path to directory containing predictions.csv
        task_name: Name of the task (for logging)
    
    Returns:
        Dict with all computed metrics, or None if predictions.csv not found
    """
    csv_path = os.path.join(task_dir, "predictions.csv")
    
    if not os.path.exists(csv_path):
        return None
    
    # Load predictions
    df = pd.read_csv(csv_path)
    
    if df.empty:
        return None
    
    y_true = df['ground_truth'].values
    y_scores = df['probability_score'].values

    # Compute metrics
    auroc = bootstrap_ci(y_true, y_scores, roc_auc_score)
    auprc = bootstrap_ci(y_true, y_scores, compute_auprc)
    f1_stats = compute_optimal_f1(y_true, y_scores)
    
    # Accuracy at 0.5 threshold
    y_pred = (y_scores > 0.5).astype(int)
    accuracy = float(np.mean(y_pred == y_true))
    
    # Load run stats if available
    run_stats = {}
    stats_path = os.path.join(task_dir, "run_stats.json")
    if os.path.exists(stats_path):
        with open(stats_path, 'r') as f:
            run_stats = json.load(f)

    summary = {
        "task_name": task_name,
        "num_examples": len(df),
        "auroc": auroc,  # [mean, ci_low, ci_high]
        "auprc": auprc,
        **f1_stats,
        "accuracy_at_0.5": accuracy,
        "mean_probability": float(np.mean(y_scores)),
        "std_probability": float(np.std(y_scores)),
        **run_stats
    }
    
    # Save per-task summary
    with open(os.path.join(task_dir, "summary.json"), 'w') as f:
        json.dump(summary, f, indent=2)

    return summary


# =============================================================================
# MAIN
# =============================================================================

def main():
    parser = argparse.ArgumentParser(
        description="Compute AUROC/AUPRC metrics from evaluation predictions"
    )
    parser.add_argument(
        "--eval_root", 
        type=str, 
        required=True,
        help="Directory containing task subdirectories with predictions.csv"
    )
    args = parser.parse_args()

    print("=" * 60)
    print("Computing Evaluation Metrics")
    print("=" * 60)
    print(f"Eval root: {args.eval_root}")
    print()

    # Process each task
    results = []
    for task in TASKS:
        task_dir = os.path.join(args.eval_root, task)
        
        if not os.path.exists(task_dir):
            print(f"  ✗ {task}: directory not found")
            continue
        
        summary = process_task_predictions(task_dir, task)
        
        if summary:
            results.append(summary)
            auroc = summary['auroc']
            auprc = summary['auprc']
            print(f"  ✓ {task}:")
            print(f"      AUROC: {auroc[0]:.4f} ({auroc[1]:.4f}-{auroc[2]:.4f})")
            print(f"      AUPRC: {auprc[0]:.4f} ({auprc[1]:.4f}-{auprc[2]:.4f})")
        else:
            print(f"  ✗ {task}: predictions.csv not found or empty")

    # Save summary CSV
    if results:
        summary_df = pd.DataFrame([
            {
                'task': r['task_name'],
                'n': r['num_examples'],
                'auroc_mean': r['auroc'][0],
                'auroc_ci_low': r['auroc'][1],
                'auroc_ci_high': r['auroc'][2],
                'auprc_mean': r['auprc'][0],
                'auprc_ci_low': r['auprc'][1],
                'auprc_ci_high': r['auprc'][2],
                'f1_optimal': r['f1'],
                'accuracy_0.5': r['accuracy_at_0.5'],
            }
            for r in results
        ])
        
        output_path = os.path.join(args.eval_root, "metrics_summary.csv")
        summary_df.to_csv(output_path, index=False)
        print(f"\nSaved: {output_path}")
    else:
        print("\nNo results to save.")

    print("\nDone!")


if __name__ == "__main__":
    main()
