#!/usr/bin/env python3
"""
Compute Metrics for Direct Y/N Evaluation

This script computes AUROC, AUPRC, and other metrics from the predictions
generated by eval_vllm_direct.py.

The script is compatible with the original eval_vllm_metric_calculator.py
but is simplified for the direct Y/N evaluation where all predictions are valid.

Usage:
    python eval_vllm_compute_metrics.py --eval_root /path/to/eval/results

Expected directory structure:
    eval_root/
    ├── acute_mi/           # Model trained on acute_mi
    │   ├── acute_mi/       # Evaluated on acute_mi task
    │   │   ├── predictions.csv
    │   │   └── run_stats.json
    │   ├── hyperlipidemia/
    │   └── ...
    ├── hyperlipidemia/
    └── ...
"""

import os
import json
import argparse
import pandas as pd
import numpy as np
from sklearn.metrics import roc_auc_score, precision_recall_curve, auc
from typing import Dict, List, Tuple, Optional


TASKS = ['acute_mi', 'pancreatic_cancer', 'hypertension', 'hyperlipidemia']


def calculate_auprc(y_true: np.ndarray, y_scores: np.ndarray) -> float:
    """Calculates Area Under Precision-Recall Curve."""
    precision, recall, _ = precision_recall_curve(y_true, y_scores)
    return auc(recall, precision)


def bootstrap_metric(
    y_true: np.ndarray, 
    y_scores: np.ndarray, 
    metric_fn, 
    n_bootstraps: int = 1000
) -> List[float]:
    """
    Compute metric with bootstrap confidence intervals.
    
    Returns:
        [mean, lower_ci (2.5%), upper_ci (97.5%)]
    """
    rng = np.random.RandomState(42)
    bootstrapped_scores = []
    
    y_true = np.array(y_true)
    y_scores = np.array(y_scores)
    
    for _ in range(n_bootstraps):
        indices = rng.randint(0, len(y_scores), len(y_scores))
        
        # Need at least two classes to calculate ROC/PRC
        if len(np.unique(y_true[indices])) < 2:
            continue
        
        try:
            score = metric_fn(y_true[indices], y_scores[indices])
            bootstrapped_scores.append(score)
        except ValueError:
            continue
    
    if not bootstrapped_scores:
        return [0.0, 0.0, 0.0]

    sorted_scores = np.sort(bootstrapped_scores)
    mean_score = np.mean(sorted_scores)
    ci_lower = np.percentile(sorted_scores, 2.5)
    ci_upper = np.percentile(sorted_scores, 97.5)
    
    return [mean_score, ci_lower, ci_upper]


def get_optimal_f1_stats(y_true: np.ndarray, y_scores: np.ndarray) -> Dict:
    """
    Calculates F1, Precision, Recall at optimal threshold.
    
    Returns dict with optimal_threshold, f1, precision, recall.
    """
    precision, recall, thresholds = precision_recall_curve(y_true, y_scores)
    
    # Avoid division by zero
    denominator = recall + precision
    f1_scores = np.divide(
        2 * recall * precision, 
        denominator, 
        out=np.zeros_like(denominator), 
        where=denominator != 0
    )
    
    best_idx = np.argmax(f1_scores) if len(f1_scores) > 0 else 0
    
    # Handle edge case where thresholds might be shorter than p/r arrays
    opt_thresh = float(thresholds[best_idx]) if best_idx < len(thresholds) else 0.5
    
    return {
        "optimal_threshold": opt_thresh,
        "f1": float(f1_scores[best_idx]) if len(f1_scores) > 0 else 0.0,
        "precision": float(precision[best_idx]) if len(precision) > 0 else 0.0,
        "recall": float(recall[best_idx]) if len(recall) > 0 else 0.0
    }


def process_single_task(folder_path: str, task_name: str) -> Optional[Dict]:
    """
    Process predictions.csv for a single task evaluation.
    
    Args:
        folder_path: Path to folder containing predictions.csv and run_stats.json
        task_name: Name of the evaluation task
    
    Returns:
        Summary dict with metrics, or None if files not found
    """
    csv_path = os.path.join(folder_path, "predictions.csv")
    stats_path = os.path.join(folder_path, "run_stats.json")
    
    if not os.path.exists(csv_path):
        return None
    
    # Read predictions
    df = pd.read_csv(csv_path)
    
    # Read run stats if available
    run_stats = {}
    if os.path.exists(stats_path):
        with open(stats_path, 'r', encoding='utf-8') as f:
            run_stats = json.load(f)

    # For direct Y/N, all predictions are valid (no parsing failures)
    # But we still support the has_valid_samples filter for compatibility
    if 'has_valid_samples' in df.columns:
        valid_df = df[df['has_valid_samples'] == True]
    else:
        valid_df = df
    
    if valid_df.empty:
        return None
    
    y_true = valid_df['ground_truth'].values
    y_scores = valid_df['probability_score'].values

    # Calculate metrics with bootstrap CIs
    auroc_stats = bootstrap_metric(y_true, y_scores, roc_auc_score)
    auprc_stats = bootstrap_metric(y_true, y_scores, calculate_auprc)
    opt_stats = get_optimal_f1_stats(y_true, y_scores)
    
    # Calculate additional stats
    mean_prob = float(np.mean(y_scores))
    std_prob = float(np.std(y_scores))
    
    # Accuracy at threshold 0.5
    y_pred = (y_scores > 0.5).astype(int)
    accuracy = float(np.mean(y_pred == y_true))

    summary = {
        "task_name": task_name,
        "num_examples": len(valid_df),
        "auroc": auroc_stats,  # [Mean, Low, High]
        "auprc": auprc_stats,  # [Mean, Low, High]
        **opt_stats,
        "accuracy_at_0.5": accuracy,
        "mean_probability": mean_prob,
        "std_probability": std_prob,
        **run_stats
    }
    
    # Save individual summary
    summary_path = os.path.join(folder_path, "summary.json")
    with open(summary_path, 'w', encoding='utf-8') as f:
        json.dump(summary, f, indent=2)

    return summary


def main():
    parser = argparse.ArgumentParser(description="Compute metrics for Direct Y/N evaluation")
    parser.add_argument("--eval_root", type=str, required=True,
                        help="Root folder containing evaluation results")
    parser.add_argument("--single_task", type=str, default=None,
                        help="If specified, only process this single task folder (not cross-task matrix)")
    args = parser.parse_args()

    print("=" * 70)
    print("Direct Y/N Metrics Computation")
    print("=" * 70)
    print(f"Evaluation root: {args.eval_root}")
    print()

    if args.single_task:
        # Process a single task folder
        task_dir = os.path.join(args.eval_root, args.single_task)
        if os.path.exists(task_dir):
            summary = process_single_task(task_dir, args.single_task)
            if summary:
                print(f"Task: {args.single_task}")
                print(f"  AUROC: {summary['auroc'][0]:.4f} ({summary['auroc'][1]:.4f}-{summary['auroc'][2]:.4f})")
                print(f"  AUPRC: {summary['auprc'][0]:.4f} ({summary['auprc'][1]:.4f}-{summary['auprc'][2]:.4f})")
                print(f"  Accuracy@0.5: {summary['accuracy_at_0.5']:.4f}")
        return

    # Create matrices for cross-task comparison (if applicable)
    auroc_matrix = pd.DataFrame(index=TASKS, columns=TASKS)
    auprc_matrix = pd.DataFrame(index=TASKS, columns=TASKS)
    
    # Also create a simple single-model results table
    single_results = []

    for source_task in TASKS:
        source_dir = os.path.join(args.eval_root, source_task)
        
        if not os.path.exists(source_dir):
            # Check if this is a flat structure (single model, multiple task evals)
            task_dir = os.path.join(args.eval_root, source_task)
            if os.path.exists(os.path.join(task_dir, "predictions.csv")):
                summary = process_single_task(task_dir, source_task)
                if summary:
                    single_results.append(summary)
            continue

        # Check for cross-task evaluation structure
        for target_task in TASKS:
            target_dir = os.path.join(source_dir, target_task)
            
            if os.path.exists(os.path.join(target_dir, "predictions.csv")):
                summary = process_single_task(target_dir, target_task)
                
                if summary:
                    roc = summary['auroc']
                    prc = summary['auprc']
                    
                    # Format: "0.850 (0.840-0.860)"
                    auroc_str = f"{roc[0]:.3f} ({roc[1]:.3f}-{roc[2]:.3f})"
                    auprc_str = f"{prc[0]:.3f} ({prc[1]:.3f}-{prc[2]:.3f})"
                    
                    auroc_matrix.loc[source_task, target_task] = auroc_str
                    auprc_matrix.loc[source_task, target_task] = auprc_str
                else:
                    auroc_matrix.loc[source_task, target_task] = "N/A"
                    auprc_matrix.loc[source_task, target_task] = "N/A"

    # Check if we have cross-task results
    has_cross_task = not auroc_matrix.isna().all().all()
    
    if has_cross_task:
        print("\n=== AUROC Table (Rows: Model, Cols: Task) ===")
        print(auroc_matrix)
        auroc_matrix.to_csv(os.path.join(args.eval_root, "final_auroc_table.csv"))

        print("\n=== AUPRC Table (Rows: Model, Cols: Task) ===")
        print(auprc_matrix)
        auprc_matrix.to_csv(os.path.join(args.eval_root, "final_auprc_table.csv"))
    
    # Print single results if available
    if single_results:
        print("\n=== Single Model Results ===")
        for result in single_results:
            print(f"\nTask: {result['task_name']}")
            print(f"  AUROC: {result['auroc'][0]:.4f} ({result['auroc'][1]:.4f}-{result['auroc'][2]:.4f})")
            print(f"  AUPRC: {result['auprc'][0]:.4f} ({result['auprc'][1]:.4f}-{result['auprc'][2]:.4f})")
            print(f"  F1@optimal: {result['f1']:.4f}")
            print(f"  Accuracy@0.5: {result['accuracy_at_0.5']:.4f}")
        
        # Save summary table
        summary_df = pd.DataFrame([
            {
                'task': r['task_name'],
                'auroc_mean': r['auroc'][0],
                'auroc_ci_low': r['auroc'][1],
                'auroc_ci_high': r['auroc'][2],
                'auprc_mean': r['auprc'][0],
                'auprc_ci_low': r['auprc'][1],
                'auprc_ci_high': r['auprc'][2],
                'f1_optimal': r['f1'],
                'accuracy_0.5': r['accuracy_at_0.5'],
            }
            for r in single_results
        ])
        summary_df.to_csv(os.path.join(args.eval_root, "metrics_summary.csv"), index=False)
        print(f"\nSaved summary to: {os.path.join(args.eval_root, 'metrics_summary.csv')}")

    print("\nDone!")


if __name__ == "__main__":
    main()
